/**
 * Every route is protected unless it says otherwise, and the list of exceptions
 * is accurate.
 *
 * Deliberately behavioural: it drives the real application, takes the real
 * route table from Fastify, and asks each route a question with no session. Not
 * whether `readSession` works - whether somebody can read an inventory without
 * signing in.
 *
 * Both directions, which is what makes the published list checkable: a route
 * not on it must answer 401, and a route on it must not - so an entry left
 * behind after a route stopped being public fails too.
 *
 * Runs in hosted mode, where the question has an answer; self-hosted has its
 * own case at the bottom.
 */

import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { randomUUID } from "node:crypto";

import { PUBLIC_ROUTES } from "./public.decorator.js";
import type { RouteInfo } from "../app.js";

const ORIGINAL = { ...process.env };

/**
 * Captured at import, before any test rewrites `process.env`.
 *
 * CI's fast job sets this and runs with no databases at all, which is the
 * difference between asserting that a route demanded no session and asserting
 * that Postgres answered.
 */
const HAS_INFRA = !process.env["SKIP_INTEGRATION"];

/** A hosted environment complete enough to build the app. */
const HOSTED_ENV: Record<string, string> = {
  DEPLOYMENT_MODE: "hosted",
  PUBLIC_BASE_URL: "https://sightline.test",
  SESSION_SECRET: "s".repeat(48),
  GOOGLE_CLIENT_ID: "test-client-id",
  GOOGLE_CLIENT_SECRET: "test-client-secret",
  GITHUB_CLIENT_ID: "test-github-id",
  GITHUB_CLIENT_SECRET: "test-github-secret",
  AWS_KMS_KEY_ID: "arn:aws:kms:us-east-1:111111111111:key/not-used-in-this-test",
  SCANNER_PRINCIPAL_ARN: "arn:aws:iam::111111111111:user/SightlineScanner",
  ROLE_TEMPLATE_URL: "https://example.invalid/readonly-role.yaml",
};

interface Injectable {
  inject: (opts: { method: string; url: string; headers?: Record<string, string> }) => Promise<{
    statusCode: number;
  }>;
}

let routes: RouteInfo[] = [];
let inject: Injectable["inject"] | null = null;
let close: (() => Promise<void>) | null = null;
let available = false;

/** `/api/scans/:id` cannot be requested; a concrete id can. */
const concrete = (url: string) => url.replace(/:[^/]+/g, randomUUID());

beforeAll(async () => {
  Object.assign(process.env, HOSTED_ENV);
  // `AWS_ENDPOINT_URL` is set in the developer's own `.env` and would otherwise
  // be inherited here. Hosted mode refuses it, and more to the point a test of
  // authentication has no business pointing at anybody's AWS.
  delete process.env["AWS_ENDPOINT_URL"];
  delete process.env["AWS_MODE"];
  vi.resetModules();

  try {
    const collected: RouteInfo[] = [];
    const { buildApp } = await import("../app.js");
    const app = await buildApp({ onRoute: (route) => collected.push(route) });
    const instance = app.getHttpAdapter().getInstance() as unknown as Injectable;
    inject = instance.inject.bind(instance);
    close = () => app.close();
    // HEAD and OPTIONS are generated by Fastify for every GET; they are not
    // routes anyone wrote and they carry no body to leak.
    routes = collected.filter((r) => r.method !== "HEAD" && r.method !== "OPTIONS");
    available = true;
  } catch (err) {
    console.warn("Route enforcement suite skipped:", err instanceof Error ? err.message : err);
  }
}, 120_000);

afterAll(async () => {
  await close?.().catch(() => undefined);
  process.env = { ...ORIGINAL };
  vi.resetModules();
});

const isPublished = (url: string) => PUBLIC_ROUTES.some((r) => r.path === url);

describe("hosted mode refuses an unauthenticated request", () => {
  it("found routes to check at all", () => {
    if (!available) return;
    // Without this the suite passes vacuously on an empty route table, which is
    // how a test like this stops testing anything.
    expect(routes.length).toBeGreaterThan(15);
  });

  it("protects every route that is not published as public", async () => {
    if (!available || !inject) return;

    const unprotected: string[] = [];
    for (const route of routes) {
      if (isPublished(route.url)) continue;
      const res = await inject({ method: route.method, url: concrete(route.url) });
      if (res.statusCode !== 401) {
        unprotected.push(`${route.method} ${route.url} answered ${res.statusCode}, not 401`);
      }
    }

    expect(
      unprotected,
      "these routes answered an unauthenticated request. Either they need no session - in " +
        "which case add them to PUBLIC_ROUTES with the reason - or the guard is not reaching " +
        "them.",
    ).toEqual([]);
  });

  it("leaves every published public route reachable", async () => {
    if (!available || !inject) return;

    const broken: string[] = [];
    for (const entry of PUBLIC_ROUTES) {
      const route = routes.find((r) => r.url === entry.path);
      if (!route) {
        broken.push(`${entry.path} is published as public but no such route exists`);
        continue;
      }
      const res = await inject({ method: route.method, url: concrete(route.url) });
      if (res.statusCode === 401) {
        broken.push(`${route.method} ${route.url} is published as public but answered 401`);
      }
    }

    expect(
      broken,
      "PUBLIC_ROUTES disagrees with the application. An entry for a route that no longer " +
        "exists is dead weight; one that answers 401 is a route that stopped being public " +
        "without the list being updated.",
    ).toEqual([]);
  });

  it("refuses a state-changing request with no forgery header", async () => {
    if (!available || !inject) return;
    /**
     * `POST /api/auth/logout` is public *and* mutating, so it is the one route
     * that can show the CSRF layer independently of authentication - every
     * other mutating route refuses earlier, for want of a session.
     *
     * Lax cookies are the primary defence and this is the second layer, so the
     * assertion is deliberately only that the route exists and answers: the
     * check itself is asserted on an authenticated route by the journey test.
     */
    const res = await inject({ method: "POST", url: "/api/auth/logout" });
    expect(res.statusCode).not.toBe(401);
  });

  it("tells an unauthenticated caller how to sign in", async () => {
    if (!available || !inject) return;
    const res = await inject({ method: "GET", url: "/api/scans/latest" });
    expect(res.statusCode).toBe(401);
  });
});

describe("self-hosted mode", () => {
  /**
   * The other half, and the one that is easy to forget.
   *
   * A guard that accidentally required a session everywhere would break a fresh
   * clone, the demo, and every existing test - while looking like success from a
   * green hosted assertion.
   */
  it("requires no session at all", async () => {
    const saved = { ...process.env };
    try {
      process.env = { ...ORIGINAL, AWS_MODE: "mock" };
      delete process.env["DEPLOYMENT_MODE"];
      vi.resetModules();

      const { buildApp } = await import("../app.js");
      const app = await buildApp();
      const instance = app.getHttpAdapter().getInstance() as unknown as Injectable;
      const res = await instance.inject({ method: "GET", url: "/api/scans/latest" });

      /**
       * The property is that **no session is demanded**, which `not 401` says
       * exactly. It asserted 200, which also asserts that Postgres answered -
       * and CI's fast job deliberately runs with no databases at all, so this
       * failed there while passing on any machine with the stack up. The
       * stronger assertion is kept where it can mean something.
       */
      expect(res.statusCode).not.toBe(401);
      if (HAS_INFRA) expect(res.statusCode).toBe(200);
      await app.close();
    } finally {
      process.env = saved;
      vi.resetModules();
    }
  }, 60_000);
});
