/**
 * Tier 1 of the eval suite: ground truth over the ingested data.
 *
 * The half that matters most, because it needs no model and no API key. It
 * verifies that the *data* the agent reasons over is correct — if these fail,
 * no amount of prompt work will make the agent right.
 *
 * It seeds the mock account, runs a genuine scan, and applies the checks in
 * `checks.ts` — the same definitions the Trust panel runs in the UI, so the
 * test suite and the product can never disagree about what "correct" means.
 *
 * The expectations those checks encode come from the answer key in
 * `topology.ts`, written by hand from the topology rather than generated by the
 * code under test, so an analyser bug cannot grade itself as correct.
 *
 * Requires the compose stack. Skipped automatically when moto is unreachable,
 * so a unit-test run on a laptop with nothing running still passes.
 */

import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { seed } from "@daveio/mock-aws";
import type { Relationship, Resource } from "@daveio/shared";

import { runScan } from "../scan/runner.js";
import { CHECKS, runChecks, type CheckResult } from "./checks.js";

let resources: Resource[] = [];
let relationships: Relationship[] = [];
let results: CheckResult[] = [];
let available = false;

beforeAll(async () => {
  try {
    const endpoint = process.env["AWS_ENDPOINT_URL"] ?? "http://localhost:5000";
    const res = await fetch(`${endpoint}/moto-api/`).catch(() => null);
    if (!res?.ok) return;

    await seed();
    const scan = await runScan({ scanId: "eval" });
    resources = scan.resources;
    relationships = scan.relationships;
    results = runChecks({ resources, relationships });
    available = true;
  } catch (err) {
    console.warn("Ground-truth suite skipped:", err instanceof Error ? err.message : err);
  }
}, 180_000);

afterAll(() => {
  if (!available) {
    console.warn(
      "\n  Ground-truth suite did not run: moto was unreachable.\n" +
        "  Start it with `docker compose up -d` to exercise these.\n",
    );
  }
});

describe.runIf(!process.env["SKIP_INTEGRATION"])("ingest ground truth", () => {
  it("collects a non-trivial inventory", () => {
    if (!available) return;
    expect(resources.length).toBeGreaterThan(50);
    expect(relationships.length).toBeGreaterThan(50);
  });

  // One test per check, so a failure names the property that broke rather than
  // reporting that "ground truth failed".
  it.each(CHECKS.map((c) => [c.id, c.description] as const))("%s: %s", (id) => {
    if (!available) return;
    const result = results.find((r) => r.id === id);
    expect(result, `check ${id} did not run`).toBeDefined();
    expect(result!.passed, `${result!.description}\n    found: ${result!.detail}`).toBe(true);
  });

  it("runs every check that is defined", () => {
    if (!available) return;
    expect(results).toHaveLength(CHECKS.length);
  });
});
