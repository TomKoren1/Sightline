/**
 * Graph and resource reads, backed by the curated query library.
 *
 * Thin by design: `db/queries.ts` is already the boundary that decides what
 * can be asked of the graph, and wrapping each query in a method that reshapes
 * it would put the same decision in two places. What this adds is the small
 * amount of policy the HTTP layer should not hold — parsing a comma-separated
 * filter, deciding that a search with no term is an empty result rather than
 * everything, and answering a connection that has never been scanned with an
 * empty graph rather than an error.
 *
 * Every method takes the scope. It is not read from anywhere ambient, because
 * an ambient tenant is correct when there is one of them and silently wrong
 * when there are many.
 */

import { Injectable, NotFoundException } from "@nestjs/common";
import type * as api from "@sightline/shared/api";

import { listFindingStates, setFindingStatus } from "../db/findings.js";
import * as q from "../db/graph.js";
import type { GraphScope } from "../db/graph.js";
import type { FindingCategory } from "../db/schema.js";
import { graphScopeFor } from "../tenancy/graphScope.js";
import type { Scope } from "../core/scope.js";
import { remediationInputFromGraph } from "../remediation/fromGraph.js";
import { remediationsFor } from "../remediation/remediation.js";
import { getConnection } from "../tenancy/connections.js";

/** Flagged resources one fix plan covers. Beyond this it says it was cut. */
const FIX_PLAN_LIMIT = 2_000;

/** Which finding category each kind of fix answers, to honour an accepted risk. */
const CATEGORY_OF: Record<api.FixPlanItem["remediation"]["addresses"], FindingCategory> = {
  public: "exposed",
  exposed: "exposed",
  admin: "admin",
  unprotected: "unguarded",
  unused: "unused",
  idle: "idle",
};

/** What a connection with no projected scan looks like. */
const EMPTY_SUMMARY = {
  byKind: [] as { kind: string; count: number }[],
  byRegion: [] as { region: string; count: number }[],
  publicCount: 0,
  adminCount: 0,
  idleCount: 0,
  idleCost: 0,
  unprotectedCount: 0,
  unusedCount: 0,
};

const EMPTY_FINDINGS = {
  publicResources: [],
  adminPrincipals: [],
  idle: [],
  exposed: [],
  unprotected: [],
  unused: [],
  accepted: [],
};

/** Each list `findings()` returns: the finder behind it, and its finding category. */
export const FINDING_LISTS = {
  publicResources: ["findPublicResources", "exposed"],
  adminPrincipals: ["findAdminPrincipals", "admin"],
  idle: ["findIdleResources", "idle"],
  exposed: ["findOpenSecurityGroups", "exposed"],
  unprotected: ["findUnprotectedBuckets", "unguarded"],
  unused: ["findUnusedAccess", "unused"],
} as const satisfies Record<api.FindingListName, readonly [q.FinderName, FindingCategory]>;
export type FindingList = keyof typeof FINDING_LISTS;

@Injectable()
export class GraphService {
  async summary(scope: Scope): Promise<api.Summary> {
    const graph = await graphScopeFor(scope);
    return graph ? q.summariseAccount(graph) : EMPTY_SUMMARY;
  }

  async graph(
    scope: Scope,
    params: { region?: string; kinds?: string; limit?: string; group?: string },
  ): Promise<api.GraphData> {
    const graph = await graphScopeFor(scope);
    if (!graph) return { nodes: [], edges: [], total: 0, truncated: false };
    const kinds = params.kinds?.split(",").filter(Boolean);
    return q.fetchGraph(graph, {
      region: params.region,
      ...(kinds && kinds.length > 0 ? { kinds } : {}),
      limit: params.limit ? Number(params.limit) : undefined,
      ...(params.group ? { group: params.group } : {}),
    });
  }

  async groups(scope: Scope): Promise<{ groups: api.GraphGroup[] }> {
    const graph = await graphScopeFor(scope);
    return { groups: graph ? await q.graphGroups(graph) : [] };
  }

  async neighbours(scope: Scope, arn: string): Promise<api.GraphData> {
    const graph = await graphScopeFor(scope);
    if (!graph) return { nodes: [], edges: [], total: 0, truncated: false };
    return q.neighbourhood(graph, arn);
  }

  async resource(scope: Scope, arn: string) {
    return { resource: await this.mustFindResource(scope, arn) };
  }

  /**
   * What you would run to fix this resource, and what it might break.
   *
   * Strictly a document: it returns strings. Nothing in this service executes
   * them, and there is deliberately no companion endpoint that does — see
   * `packages/shared/src/remediation.ts`. The commands are computed from the
   * same evidence the verdict came from, not generated by the model.
   */
  async remediation(scope: Scope, arn: string) {
    const resource = await this.mustFindResource(scope, arn);
    return {
      arn: resource.arn,
      remediations: remediationsFor(remediationInputFromGraph(resource)),
      note: "Generated for you to review and run yourself. Sightline holds read-only access and will never apply these.",
    };
  }

  /**
   * Every computed fix for the account's open findings, for the fix plan.
   *
   * The same documents as `remediation`, gathered: still strings for a person
   * to choose from, read and run. A fix for a finding someone accepted as a
   * risk is left out - accepting it was the decision not to fix it.
   */
  async fixPlan(scope: Scope): Promise<api.FixPlan> {
    const graph = await graphScopeFor(scope);
    if (!graph)
      return { accountId: null, scanId: null, items: [], withoutFix: [], truncated: false };
    const [{ resources, truncated }, accepted, connection] = await Promise.all([
      q.flaggedResources(graph, FIX_PLAN_LIMIT),
      listFindingStates(scope, { acceptedOr: [] }),
      getConnection(scope),
    ]);
    const acceptedKey = new Set(
      accepted.filter((f) => f.status === "accepted").map((f) => `${f.category}|${f.resourceArn}`),
    );
    const items: api.FixPlanItem[] = [];
    const withoutFix: api.FixPlan["withoutFix"] = [];
    for (const resource of resources) {
      const fixes = remediationsFor(remediationInputFromGraph(resource)).filter(
        (r) => !acceptedKey.has(`${CATEGORY_OF[r.addresses]}|${resource.arn}`),
      );
      const where = {
        arn: resource.arn,
        name: resource.name,
        kind: resource.kind,
        region: resource.region,
      };
      if (fixes.length === 0)
        withoutFix.push({ arn: where.arn, name: where.name, kind: where.kind });
      for (const remediation of fixes) items.push({ ...where, remediation });
    }
    return {
      accountId: connection?.accountId ?? null,
      scanId: graph.scanId,
      items,
      withoutFix,
      truncated,
    };
  }

  async search(scope: Scope, text?: string) {
    const graph = await graphScopeFor(scope);
    // No term is an empty result, not the whole account.
    if (!graph || !text) return { results: [] };
    return { results: await q.searchResources(graph, { text }) };
  }

  /**
   * Findings, for the dashboard panels.
   *
   * Each item carries its tracked state, when it has one, so the UI can say
   * how long it has been open and offer to accept it. Accepted findings leave
   * the lists they would otherwise sit in and are returned on their own: a
   * decision somebody made should not keep shouting from the same place as
   * the things nobody has looked at yet.
   */
  async findings(scope: Scope) {
    const graph = await graphScopeFor(scope);
    if (!graph) return EMPTY_FINDINGS;

    // Fetch past the accepted ones, so hiding them does not shorten the list.
    const acceptedCount = (await listFindingStates(scope, { acceptedOr: [] })).length;
    const limit = 50 + acceptedCount;

    const [publicResources, adminPrincipals, idle, exposed, unprotected, unused] =
      await Promise.all([
        q.findPublicResources(graph, { limit }),
        q.findAdminPrincipals(graph, { limit }),
        q.findIdleResources(graph, { limit }),
        q.findOpenSecurityGroups(graph, { limit }),
        q.findUnprotectedBuckets(graph, { limit }),
        q.findUnusedAccess(graph, { limit }),
      ]);

    // Only the states of what is about to be shown, plus every acceptance.
    const shown = [publicResources, adminPrincipals, idle, exposed, unprotected, unused].flatMap(
      (rows) => rows.map((row) => row.arn),
    );
    const states = await listFindingStates(scope, { acceptedOr: shown });
    const tracked = new Map(states.map((s) => [`${s.category} ${s.resourceArn}`, s]));

    const annotate = <T extends q.ResourceRow>(category: FindingCategory, rows: T[]) =>
      rows
        .map((row) => {
          const state = tracked.get(`${category} ${row.arn}`);
          return {
            ...row,
            finding: state
              ? { id: state.id, status: state.status, firstSeenAt: state.firstSeenAt }
              : null,
          };
        })
        .filter((row) => row.finding?.status !== "accepted")
        .slice(0, 50);

    // Only what the current scan still shows: an acceptance of a finding a
    // partial scan did not reach is kept, but not listed as if it were seen.
    const accepted = states
      .filter((s) => s.status === "accepted" && s.lastScanId === graph.scanId)
      .map((s) => ({
        arn: s.resourceArn,
        kind: s.resourceKind,
        name: s.resourceName,
        region: null,
        category: s.category,
        reason: s.reason,
        finding: {
          id: s.id,
          status: s.status,
          firstSeenAt: s.firstSeenAt,
          statusReason: s.statusReason,
          statusAt: s.statusAt,
        },
      }));

    return {
      publicResources: annotate("exposed", publicResources),
      adminPrincipals: annotate("admin", adminPrincipals),
      idle: annotate("idle", idle),
      // Internet-reachable through a rule: the same exposure, named differently.
      exposed: annotate("exposed", exposed),
      unprotected: annotate("unguarded", unprotected),
      unused: annotate("unused", unused),
      accepted,
    };
  }

  /**
   * The next page of one findings list, past the 50 `findings()` returns.
   *
   * Offsets count the whole list, accepted findings included, because the
   * finders know nothing of finding state; accepted ones are then hidden as
   * on the first page. A caller asking from the number it has shown may see a
   * few rows again, never miss one, and follows `next` from there.
   */
  async findingsPage(scope: Scope, list: FindingList, offset: number) {
    const graph = await graphScopeFor(scope);
    if (!graph) return { rows: [], total: 0, offset: 0, next: null };
    const [finder, category] = FINDING_LISTS[list];
    const page = await q.pageOf(finder, graph, { limit: 50, offset });
    const states = await listFindingStates(scope, { acceptedOr: page.rows.map((r) => r.arn) });
    const tracked = new Map(states.map((st) => [`${st.category} ${st.resourceArn}`, st]));
    const rows = page.rows
      .map((row) => {
        const state = tracked.get(`${category} ${row.arn}`);
        return {
          ...row,
          finding: state
            ? { id: state.id, status: state.status, firstSeenAt: state.firstSeenAt }
            : null,
        };
      })
      .filter((row) => row.finding?.status !== "accepted");
    const end = page.offset + page.rows.length;
    return { rows, total: page.total, offset: page.offset, next: end < page.total ? end : null };
  }

  /** Accept a finding's risk with a reason, or reopen it. */
  async setFindingStatus(
    scope: Scope,
    input: {
      id: string;
      status: "accepted" | "open";
      reason: string | null;
      actorUserId: string | null;
    },
  ) {
    const finding = await setFindingStatus(scope, input);
    if (!finding) throw new NotFoundException({ error: "No such open finding" });
    return { finding };
  }

  /**
   * A resource in this tenant's current graph, or 404.
   *
   * A connection with no scan gives the same answer as an ARN that does not
   * exist, deliberately: both mean "not in your graph", and distinguishing
   * them would tell a caller whether an ARN exists in *somebody's* graph.
   */
  private async mustFindResource(scope: Scope, arn: string) {
    const graph: GraphScope | null = await graphScopeFor(scope);
    const resource = graph ? await q.getResource(graph, decodeURIComponent(arn)) : null;
    if (!resource) throw new NotFoundException({ error: "No such resource" });
    return resource;
  }
}
